use crate::wasm4::*;

pub struct Image<'a> {
    w: u32,
    h: u32,
    flags: u32,
    data: &'a[u8],
}

impl Image<'_> {
    pub fn draw(&self, x: i32, y: i32, flags: u32){
        blit(self.data, x, y, self.w, self.h, self.flags | flags);
    }
}


